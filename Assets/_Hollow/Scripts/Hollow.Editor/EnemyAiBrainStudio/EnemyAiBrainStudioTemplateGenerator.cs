        [MenuItem("Hollow/Enemy Authoring/Generate Enemy AI Brain Templates")]
        public static void GenerateAssets()
        {
            Directory.CreateDirectory(TemplateFolder);
            foreach (var template in CreateRuntimeTemplates())
            {
                var path = $"{TemplateFolder}/{SanitizeFileName(template.TemplateId)}.asset";
                var existing = AssetDatabase.LoadAssetAtPath<EnemyAiBrainTemplateDefinition>(path);
                if (existing == null)
                {
                    AssetDatabase.CreateAsset(template, path);
                }
                else
                {
                    EditorUtility.CopySerialized(template, existing);
                    existing.name = template.TemplateId;
                    EditorUtility.SetDirty(existing);
                    UnityEngine.Object.DestroyImmediate(template);
                }
            }

            AssetDatabase.SaveAssets();
            AssetDatabase.Refresh();
        }

