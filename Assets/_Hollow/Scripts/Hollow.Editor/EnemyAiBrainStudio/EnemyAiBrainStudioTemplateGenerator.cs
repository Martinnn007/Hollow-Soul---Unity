        private static EnemyAiBrainTemplateDefinition Template(
            string id,
            string displayName,
            string description,
            EnemyAiBrainTemplateRole role,
            IEnumerable<EnemyBehaviorId> behaviors,
            IEnumerable<EnemyInstinctDisposition> dispositions,
            EnemyIntelligenceLevel intelligence,
            EnemyInstinctDisposition disposition,
            bool bossMetadataOnly,
            float speed,
            float radius,
            float sight,
            float angle,
            float hearing,
            float sensitivity,
            float threshold,
            float investigate,
            bool alert,
            float alertRadius,
            float alertCooldown,
            EnemyAwarenessState alertAwareness,
            float windup,
            float active,
            float recovery,
            float hitArcBonus,
            int poiseOffset,
            float ideal,
            float closeTolerance,
            float longTolerance,
            float pressureBias,
            int resets,
            string notes)
        {
            var template = ScriptableObject.CreateInstance<EnemyAiBrainTemplateDefinition>();
            template.name = id;
            template.Configure(
                id,
                displayName,
                description,
                role,
                behaviors,
                dispositions,
                intelligence,
                disposition,
                bossMetadataOnly,
                speed,
                radius,
                sight,
                angle,
                hearing,
                sensitivity,
                threshold,
                investigate,
                alert,
                alertRadius,
                alertCooldown,
                alertAwareness,
                windup,
                active,
                recovery,
                hitArcBonus,
                poiseOffset,
                ideal,
                closeTolerance,
                longTolerance,
                pressureBias,
                resets,
                notes);
            return template;
        }

        private static string SanitizeFileName(string value)
        {
            var invalid = Path.GetInvalidFileNameChars();
            return new string((value ?? "template").Select(character => invalid.Contains(character) ? '_' : character).ToArray());
        }
